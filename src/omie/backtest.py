"""Walk-forward backtest of day-ahead price forecasts.

For each month in the test period, the models are trained on all days *before* that
month and then forecast every day of the month (24 hours at a time, using only
information known the day before; see ``omie.features``). This mimics a forecaster
who retrains once a month and never sees the future.

Models:
    naive_24h    same hour, previous day
    naive_168h   same hour, same weekday last week
    ridge        linear regression (Ridge) on the features, one-hot calendar
    lgbm         gradient boosting (LightGBM) on the features

Usage:
    python -m omie.backtest                      # Portugal, test from 2024-01
    python -m omie.backtest --price price_es --test-start 2023-01
"""

from __future__ import annotations

import argparse
import time

import lightgbm as lgb
import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.linear_model import Ridge
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

from omie.config import DATA_PROCESSED, ROOT
from omie.data import load_hourly
from omie.features import CATEGORICAL, FEATURES, build_features, to_panel

MODELS = ["naive_24h", "naive_168h", "ridge", "lgbm"]
BENCHMARK = "naive_24h"
NUMERIC = [f for f in FEATURES if f not in CATEGORICAL]


def make_ridge():
    prep = ColumnTransformer(
        [
            ("num", StandardScaler(), NUMERIC),
            ("cat", OneHotEncoder(handle_unknown="ignore"), CATEGORICAL),
        ]
    )
    return make_pipeline(prep, Ridge(alpha=1.0))


def make_lgbm():
    return lgb.LGBMRegressor(
        n_estimators=500,
        learning_rate=0.05,
        num_leaves=31,
        min_child_samples=50,
        subsample=0.8,
        subsample_freq=1,
        colsample_bytree=0.8,
        random_state=42,
        verbose=-1,
    )


def monthly_splits(dates: pd.Series, test_start: str):
    """Yield (month_start, train_mask, test_mask) for each month from ``test_start``.

    Training data always ends the day before the test month starts.
    """
    first = pd.Timestamp(test_start).to_period("M")
    last = dates.max().to_period("M")
    for month in pd.period_range(first, last, freq="M"):
        start, end = month.start_time, (month + 1).start_time
        yield start, dates < start, (dates >= start) & (dates < end)


def run_backtest(
    features: pd.DataFrame, test_start: str = "2024-01", verbose: bool = True
) -> pd.DataFrame:
    """Return one row per forecast (date, hour) with the actual price and each model's forecast."""
    results = []
    for start, train, test in monthly_splits(features["date"], test_start):
        tr, te = features[train], features[test]
        if te.empty:
            continue
        out = te[["date", "hour", "price"]].copy()
        out["naive_24h"] = te["lag_1d"].to_numpy()
        out["naive_168h"] = te["lag_7d"].to_numpy()

        ridge = make_ridge().fit(tr[FEATURES], tr["price"])
        out["ridge"] = ridge.predict(te[FEATURES])

        lgbm = make_lgbm().fit(tr[FEATURES], tr["price"])
        out["lgbm"] = lgbm.predict(te[FEATURES])

        results.append(out)
        if verbose:
            print(f"{start:%Y-%m}: trained on {len(tr):,} rows, forecast {len(te):,}")
    return pd.concat(results, ignore_index=True).rename(columns={"price": "actual"})


# --------------------------------------------------------------------------- metrics
def metrics(forecasts: pd.DataFrame, by: str | None = None) -> pd.DataFrame:
    """MAE, RMSE and relative MAE (model MAE / naive_24h MAE), overall or grouped."""
    errors = forecasts[MODELS].sub(forecasts["actual"], axis=0)
    keys = forecasts[by] if by else pd.Series("all", index=forecasts.index, name="period")
    mae = errors.abs().groupby(keys).mean()
    rmse = errors.pow(2).groupby(keys).mean().pow(0.5)
    rel = mae.div(mae[BENCHMARK], axis=0)
    return pd.concat({"MAE": mae, "RMSE": rmse, "rel_MAE": rel}, axis=1)


def metrics_report(forecasts: pd.DataFrame, price_col: str, test_start: str) -> str:
    fc = forecasts.assign(year=forecasts["date"].dt.year)
    overall, yearly = metrics(fc), metrics(fc, by="year")
    first, last = fc["date"].min(), fc["date"].max()

    def table(m: pd.DataFrame, kind: str) -> str:
        return m[kind].round(3 if kind == "rel_MAE" else 2).to_markdown()

    lines = [
        "# Day-ahead forecast backtest: metrics",
        "",
        "Generated by `python -m omie.backtest`.",
        "",
        f"- Price: `{price_col}` (EUR/MWh)",
        f"- Test period: {first:%Y-%m-%d} to {last:%Y-%m-%d} ({len(fc):,} hourly forecasts)",
        "- Walk-forward: retrained every month on all earlier data",
        f"- Benchmark for relative MAE: `{BENCHMARK}` (below 1 = better than the benchmark)",
        "",
        "## Overall",
        "",
        "**MAE**",
        "",
        table(overall, "MAE"),
        "",
        "**RMSE**",
        "",
        table(overall, "RMSE"),
        "",
        "**Relative MAE**",
        "",
        table(overall, "rel_MAE"),
        "",
        "## By year",
        "",
        "**MAE**",
        "",
        table(yearly, "MAE"),
        "",
        "**Relative MAE**",
        "",
        table(yearly, "rel_MAE"),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Walk-forward backtest of day-ahead forecasts")
    parser.add_argument("--price", default="price_pt", choices=["price_pt", "price_es"])
    parser.add_argument("--test-start", default="2024-01", help="first test month, YYYY-MM")
    args = parser.parse_args()

    t0 = time.time()
    features = build_features(to_panel(load_hourly(), args.price))
    forecasts = run_backtest(features, args.test_start)

    out = DATA_PROCESSED / "forecasts.parquet"
    forecasts.to_parquet(out, index=False)
    report = ROOT / "reports" / "forecast_metrics.md"
    report.write_text(metrics_report(forecasts, args.price, args.test_start), encoding="utf-8")

    print()
    print(metrics(forecasts)["MAE"].round(2).to_string())
    print(metrics(forecasts)["rel_MAE"].round(3).to_string())
    print(f"\nforecasts: {out}\nreport: {report}\n({time.time() - t0:.0f} s)")


if __name__ == "__main__":
    np.random.seed(42)
    main()
